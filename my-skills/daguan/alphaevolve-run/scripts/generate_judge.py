def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate judge.py for AlphaEvolve")
    parser.add_argument("--input-dir", required=True, help="Path to input directory")
    parser.add_argument("--task-type", required=True, choices=["mle", "prompt"], help="Task type")
    parser.add_argument("--output", help="Output path (default: <input-dir>/judge.py)")
    parser.add_argument("--dry-run", action="store_true", help="Print generated code without writing")
    parser.add_argument("--metrics", help="Comma-separated metric keys for MLE combined_score")
    return parser.parse_args()


def analyze_agent_return(agent_path: Path) -> Optional[List[str]]:
    """分析 agent.py 的 main 函数返回的 metrics 字段"""
    try:
        source = agent_path.read_text(encoding="utf-8")
        tree = ast.parse(source)
        
        # 查找 main 函数中的 return 语句
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef) and node.name == "main":
                for child in ast.walk(node):
                    if isinstance(child, ast.Return) and child.value:
                        # 尝试解析 dict 字面量
                        if isinstance(child.value, ast.Dict):
                            keys = []
                            for k in child.value.keys:
                                if isinstance(k, ast.Constant):
                                    keys.append(k.value)
                                elif isinstance(k, ast.Str):  # Python 3.7 兼容
                                    keys.append(k.s)
                            return keys
        return None
    except Exception:
        return None


def analyze_data_columns(data_path: Path) -> Optional[List[str]]:
    """分析数据文件的列名"""
    try:
        if data_path.suffix == ".csv":
            import csv
            with open(data_path, "r", encoding="utf-8") as f:
                reader = csv.reader(f)
                headers = next(reader, None)
                return headers
        elif data_path.suffix == ".jsonl":
            with open(data_path, "r", encoding="utf-8") as f:
                line = f.readline().strip()
                if line:
                    data = json.loads(line)
                    return list(data.keys())
        return None
    except Exception:
        return None


