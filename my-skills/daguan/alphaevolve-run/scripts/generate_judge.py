def main() -> int:
    args = parse_args()
    input_dir = Path(args.input_dir).resolve()
    output_path = Path(args.output) if args.output else input_dir / "judge.py"
    
    agent_path = input_dir / "agent.py"
    if not agent_path.exists():
        print(f"[ERROR] agent.py not found: {agent_path}")
        return 1
    
    # 生成 judge.py
    if args.task_type == "mle":
        metrics = None
        if args.metrics:
            metrics = [m.strip() for m in args.metrics.split(",") if m.strip()]
            print(f"[INFO] Using metrics from --metrics: {metrics}")
        else:
            metrics = analyze_agent_return(agent_path)
            if metrics:
                print(f"[INFO] Detected metrics from agent.py: {metrics}")
            else:
                print("[ERROR] Could not detect metrics from agent.py; pass --metrics")
                return 2

        code = generate_mle_judge(input_dir, metrics)
    else:
        code = generate_prompt_judge(input_dir)
    
    if args.dry_run:
        print("[DRY RUN] Generated judge.py:")
        print("=" * 60)
        print(code)
        print("=" * 60)
    else:
        output_path.write_text(code, encoding="utf-8")
        print(f"[OK] Generated judge.py: {output_path}")
    
    return 0


if __name__ == "__main__":
    sys.exit(main())
